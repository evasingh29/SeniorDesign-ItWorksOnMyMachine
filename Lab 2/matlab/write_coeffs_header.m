function write_coeffs_header(sos, g, fs, note)
% WRITE_COEFFS_HEADER  Write SOS filter coefficients to firmware/filter_coeffs.h
%
%   write_coeffs_header(sos, g, fs)
%   write_coeffs_header(sos, g, fs, note)
%
%   sos  : N-by-6 matrix, rows [b0 b1 b2 a0 a1 a2] (from zp2sos or filterDesigner export)
%   g    : overall gain (scalar). Use 1 if it's already folded into sos.
%          filterDesigner may export G as a vector, one per section; that's handled too.
%   fs   : sample rate in Hz (must be what the Arduino runs at)

if nargin < 4, note = ''; end

% Fold the gain into the numerators so the Arduino only needs the SOS matrix
if isscalar(g)
    sos(1,1:3) = sos(1,1:3) * g;
else
    for i = 1:size(sos,1)
        sos(i,1:3) = sos(i,1:3) * g(i);
    end
    if numel(g) > size(sos,1)                    % extra output gain from filterDesigner
        sos(end,1:3) = sos(end,1:3) * prod(g(size(sos,1)+1:end));
    end
end

% Normalize so a0 = 1 in every section (the Arduino code assumes it)
for i = 1:size(sos,1)
    sos(i,:) = sos(i,:) / sos(i,4);
end

here = fileparts(mfilename('fullpath'));
outFile = fullfile(here, '..', 'firmware', 'filter_coeffs.h');
fid = fopen(outFile, 'w');
if fid < 0, error('Could not open %s for writing', outFile); end

fprintf(fid, '// AUTO-GENERATED by matlab/design_filter.m. Don''t edit by hand, rerun the script.\n');
if ~isempty(note), fprintf(fid, '// %s, fs %g Hz\n', note, fs); end
fprintf(fid, '// Each row: b0, b1, b2, a0, a1, a2\n');
fprintf(fid, '#pragma once\n\n');
fprintf(fid, '#define FS %d\n', round(fs));
fprintf(fid, '#define NUM_SECTIONS %d\n\n', size(sos,1));
fprintf(fid, 'const float SOS[NUM_SECTIONS][6] = {\n');
for i = 1:size(sos,1)
    fprintf(fid, '  {%.9ef, %.9ef, %.9ef, %.9ef, %.9ef, %.9ef}', sos(i,:));
    if i < size(sos,1), fprintf(fid, ','); end
    fprintf(fid, '\n');
end
fprintf(fid, '};\n');
fclose(fid);

fprintf('Wrote %s (%d sections)\n', outFile, size(sos,1));
end
